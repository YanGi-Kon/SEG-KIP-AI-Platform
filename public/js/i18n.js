window.currentLang = localStorage.getItem(I18N_LANG_KEY) || 'uz';

window.setLanguage = function (lang) {
  if (TRANSLATIONS[lang]) {
    window.currentLang = lang;
    localStorage.setItem(I18N_LANG_KEY, lang);
    window.applyTranslations();
  }
};

window.applyTranslations = function (root = document) {
  const dict = TRANSLATIONS[window.currentLang];
  if (!dict) return;

  // 1. Translate elements with data-i18n
  const elements = root.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      // Preserve HTML if it has inner elements, but here we just set textContent mostly.
      // Wait, some elements might just need textContent.
      el.textContent = dict[key];
    }
  });

  // 2. If running in the main window, translate accessible iframes
  if (root === document) {
    const iframes = document.querySelectorAll('iframe');
    iframes.forEach(iframe => {
      try {
        const idoc = iframe.contentWindow?.document;
        if (idoc) window.applyTranslations(idoc);
      } catch (e) {
        // Ignore cross-origin or not-loaded errors
      }
    });
  }
};

// Apply translations on load
document.addEventListener('DOMContentLoaded', () => {
  window.applyTranslations();
});
